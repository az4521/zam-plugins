// Refreshes zam-api/ from a Zam checkout: the plugin API's TypeScript
// declarations (src/lib/plugins/types.ts and the types it uses) and the
// Java interfaces Android native hosts implement. Run it when Zam's plugin
// API changes, and commit the result.
// usage: node scripts/sync-zam-api.mjs <path to a Zam checkout>
import {
    copyFileSync,
    mkdirSync,
    readFileSync,
    rmSync,
    writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "zam-api");
const zam = resolve(process.argv[2] ?? "");
const pluginsDir = join(zam, "src", "lib", "plugins");
const entry = join(pluginsDir, "types.ts");
const pkg = JSON.parse(readFileSync(join(zam, "package.json"), "utf8"));

// Declarations only, for the files the API's types reach.
const files = {};
const program = ts.createProgram([entry], {
    declaration: true,
    emitDeclarationOnly: true,
    skipLibCheck: true,
    strict: true,
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    baseUrl: zam,
    paths: { "$lib/*": ["src/lib/*"] },
    noEmitOnError: false,
});
program.emit(undefined, (name, text) => {
    files[resolve(name)] = text;
});
const wanted = new Set();
const visit = (src) => {
    const dts = src.replace(/\.ts$/, ".d.ts");
    if (wanted.has(dts) || !files[dts]) return;
    wanted.add(dts);
    for (const m of files[dts].matchAll(/from "(\.\/[^"]+)"/g))
        visit(join(dirname(src), m[1]) + ".ts");
};
visit(entry);
if (!wanted.size) throw new Error(`no declarations for ${entry}`);

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "plugins"), { recursive: true });
for (const f of wanted) {
    const to = join(out, "plugins", relative(pluginsDir, f));
    if (to.startsWith("..")) throw new Error(`${f} is outside src/lib/plugins`);
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, files[f]);
}
const java = join(
    zam,
    "android",
    "app",
    "src",
    "main",
    "java",
    "moe",
    "crafty",
    "matrix",
);
for (const f of ["PluginNativeHost.java", "PluginNativePort.java"])
    copyFileSync(join(java, f), join(out, f));
writeFileSync(
    join(out, "README.md"),
    `# Zam's plugin API, as of Zam ${pkg.version}

Generated by \`node scripts/sync-zam-api.mjs <Zam checkout>\`; don't edit.

- \`plugins/types.d.ts\`: \`ZamPluginApi\` (the \`zam\` object a plugin's onload
  gets), \`PluginModule\` and what they use.
- \`PluginNativeHost.java\`, \`PluginNativePort.java\`: what an Android native
  host (\`native.platforms["android-*"]\`) implements; compile-only.
`,
);
console.log(
    `zam-api: ${wanted.size} declaration files and the Java interfaces from Zam ${pkg.version}`,
);
